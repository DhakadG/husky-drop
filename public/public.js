function uiIcon(name, className = "ico") {
  if (!UI_ICON_NAMES.has(name)) throw new Error(`Unknown icon: ${name}`);
  const classes = className === "ico" ? "ico" : `ico ${className}`;
  return `<svg class="${classes}" aria-hidden="true"><use href="/icons.svg#${name}"></use></svg>`;
}

